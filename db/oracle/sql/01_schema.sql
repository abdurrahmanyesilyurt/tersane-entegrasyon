-- Oracle (PL/SQL) counterpart of the SQL Server integration schema — a learning/comparison example.
-- Same ideas as src/Tersane.Data/Sql: material request, transactional outbox, integration log, stock.
-- Runs on Oracle Database Free 23ai; written to stay compatible with 19c (no 23ai-only syntax).
WHENEVER SQLERROR EXIT FAILURE ROLLBACK
SET ECHO OFF FEEDBACK OFF

CREATE SEQUENCE seq_material_request START WITH 1 NOCACHE;

CREATE TABLE material_requests
(
    id            NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_material_requests PRIMARY KEY,
    request_seq   NUMBER DEFAULT seq_material_request.NEXTVAL NOT NULL,
    created_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    -- Virtual column = SQL Server's PERSISTED computed column. Only deterministic expressions are allowed,
    -- hence TO_CHAR with explicit format models (no NLS dependency).
    request_no    VARCHAR2(20) GENERATED ALWAYS AS
                  ('MT-' || TO_CHAR(EXTRACT(YEAR FROM created_at), 'FM0000') || '-' || TO_CHAR(request_seq, 'FM00000')) VIRTUAL,
    hull_no       VARCHAR2(20)  NOT NULL,
    status        VARCHAR2(20)  DEFAULT 'Draft' NOT NULL
                  CONSTRAINT ck_material_requests_status
                  CHECK (status IN ('Draft', 'Submitted', 'SentToErp', 'ApprovedInErp', 'Received', 'Rejected', 'Failed')),
    requested_by  VARCHAR2(100) NOT NULL,
    need_date     DATE          NOT NULL,
    submitted_at  TIMESTAMP,
    CONSTRAINT uq_material_requests_no UNIQUE (request_no)
);

CREATE TABLE material_request_lines
(
    id          NUMBER GENERATED ALWAYS AS IDENTITY CONSTRAINT pk_material_request_lines PRIMARY KEY,
    request_id  NUMBER        NOT NULL CONSTRAINT fk_mrl_request REFERENCES material_requests (id) ON DELETE CASCADE,
    line_no     NUMBER(4)     NOT NULL,
    part_no     VARCHAR2(40)  NOT NULL,
    quantity    NUMBER(18, 3) NOT NULL CONSTRAINT ck_mrl_quantity CHECK (quantity > 0),
    unit        VARCHAR2(10)  NOT NULL,
    CONSTRAINT uq_mrl_line UNIQUE (request_id, line_no)
);

CREATE TABLE outbox_messages
(
    id               NUMBER GENERATED ALWAYS AS IDENTITY CONSTRAINT pk_outbox_messages PRIMARY KEY,
    message_id       RAW(16)        DEFAULT SYS_GUID() NOT NULL CONSTRAINT uq_outbox_message_id UNIQUE,
    message_type     VARCHAR2(100)  NOT NULL,
    aggregate_id     VARCHAR2(50)   NOT NULL,
    idempotency_key  VARCHAR2(200)  NOT NULL CONSTRAINT uq_outbox_idempotency UNIQUE,
    payload          CLOB           CONSTRAINT ck_outbox_payload_json CHECK (payload IS JSON),
    status           VARCHAR2(20)   DEFAULT 'Pending' NOT NULL
                     CONSTRAINT ck_outbox_status CHECK (status IN ('Pending', 'Processing', 'Processed', 'Failed')),
    attempt_count    NUMBER         DEFAULT 0 NOT NULL,
    max_attempts     NUMBER         DEFAULT 5 NOT NULL,
    next_attempt_at  TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    locked_by        VARCHAR2(100),
    locked_until     TIMESTAMP,
    last_error       VARCHAR2(2000),
    created_at       TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX ix_outbox_due ON outbox_messages (status, next_attempt_at);

CREATE TABLE integration_logs
(
    id           NUMBER GENERATED ALWAYS AS IDENTITY CONSTRAINT pk_integration_logs PRIMARY KEY,
    occurred_at  TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    operation    VARCHAR2(100)  NOT NULL,
    log_level    VARCHAR2(10)   NOT NULL,
    message_id   RAW(16),
    message      VARCHAR2(2000) NOT NULL
);

CREATE TABLE stock_balances
(
    part_no         VARCHAR2(40)  NOT NULL,
    location_no     VARCHAR2(20)  NOT NULL,
    qty_on_hand     NUMBER(18, 3) NOT NULL,
    qty_reserved    NUMBER(18, 3) NOT NULL,
    erp_changed_at  TIMESTAMP     NOT NULL,
    synced_at       TIMESTAMP     NOT NULL,
    CONSTRAINT pk_stock_balances PRIMARY KEY (part_no, location_no)
);

-- SQL-level collection types = SQL Server's table-valued parameter type.
CREATE TYPE t_stock_row AS OBJECT
(
    part_no         VARCHAR2(40),
    location_no     VARCHAR2(20),
    qty_on_hand     NUMBER(18, 3),
    qty_reserved    NUMBER(18, 3),
    erp_changed_at  TIMESTAMP
);
/
CREATE TYPE t_stock_rows AS TABLE OF t_stock_row;
/
CREATE TYPE t_id_list AS TABLE OF NUMBER;
/

PROMPT schema created
EXIT
